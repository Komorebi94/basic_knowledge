import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { runInNewContext } from "node:vm";
import ts from "typescript";
const source = await readFile(new URL("../src/domain/review.ts", import.meta.url), "utf8");
const exports = {};
runInNewContext(ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText, { exports, Intl, Date, Set, Map }, { timeout: 1000 });
const r = exports;
const now = "2026-03-08T06:30:00.000Z";
const preferences = { dailyLimit: 20, studyTimezone: "America/New_York" };
const card = (index, revision = 1) => ({ cardId: `card-${String(index).padStart(3,"0")}`, catalogId: "K01-01", sourceContentId: "K01-01", sourceRevision: 1, cardRevision: revision, question: `问题 ${index}`, answerPoints: ["机制"], pitfalls: ["边界"], sourceHeadingId: "problem", order: index + 1 });
const cards = Array.from({ length: 50 }, (_, index) => card(index));
const json = (value) => JSON.parse(JSON.stringify(value));
assert.deepEqual(json(r.nextSchedule(0,"forgotten")), {stage:0,intervalDays:1});
assert.deepEqual(json(r.nextSchedule(0,"unstable")), {stage:0,intervalDays:1});
assert.deepEqual(json(r.nextSchedule(0,"remembered")), {stage:1,intervalDays:1});
assert.deepEqual(json(r.nextSchedule(0,"fluent")), {stage:2,intervalDays:3});
assert.deepEqual(json(r.nextSchedule(6,"remembered")), {stage:6,intervalDays:60});
assert.deepEqual(json(r.nextSchedule(6,"unstable")), {stage:5,intervalDays:1});
assert.equal(r.studyDate("2026-03-08T04:59:59.000Z", "America/New_York"), "2026-03-07");
assert.equal(r.studyDate("2026-03-08T05:00:00.000Z", "America/New_York"), "2026-03-08");
assert.equal(r.addCalendarDays("2026-03-08",1), "2026-03-09");
assert.equal(r.addCalendarDays("2026-11-01",1), "2026-11-02");
assert.equal(r.addCalendarDays("2028-02-28",1), "2028-02-29");
assert.throws(() => r.addCalendarDays("2026-02-30",1));
assert.throws(() => r.studyDate(now,"Unknown/Zone"));
let state = r.subscribeContent(r.emptyReviewState(), cards.slice(0,5), now);
state = r.startReviewSession(state, cards, preferences, now, "s1");
assert.equal(state.sessions.s1.cardsSnapshot.length,5);
assert.equal(r.startReviewSession(state,cards,preferences,now,"another").activeSessionId,"s1");
assert.throws(() => r.rateReviewCard(state,"s1",1,"remembered","e1",now,cards,preferences.studyTimezone));
state = r.saveReviewAnswer(state,"s1",1,"我能解释",true);
assert.equal(state.sessions.s1.answerDraft,"我能解释");
assert.equal(state.sessions.s1.answerRevealed,true);
const before = state;
state = r.rateReviewCard(state,"s1",2,"remembered","e1",now,cards,preferences.studyTimezone);
assert.equal(state.sessions.s1.cursor,1);
assert.equal(state.sessions.s1.answerRevealed,false);
assert.equal(state.sessions.s1.answerDraft,"");
assert.equal(state.progress[cards[0].cardId].dueDate,"2026-03-09");
assert.equal(r.rateReviewCard(state,"s1",2,"remembered","e1",now,cards,preferences.studyTimezone),state);
assert.throws(() => r.rateReviewCard(state,"s1",2,"forgotten","another-e1",now,cards,preferences.studyTimezone));
assert.equal(before.sessions.s1.cursor,0,"领域函数不原地更改旧状态");
assert.equal(r.isReviewState(state),true);
assert.equal(r.getReviewSummary(state,cards,preferences,now).todayCompleted,1);
state = r.undoLastReview(state,"s1",state.sessions.s1.revision,now);
assert.equal(state.sessions.s1.cursor,0);
assert.equal(state.progress[cards[0].cardId].lastRating,null);
assert.equal(r.getReviewSummary(state,cards,preferences,now).todayCompleted,0);
assert.equal(r.getReviewSummary(state,cards,preferences,now).newRemaining,5);
assert.equal(r.isReviewState(state),true);
state = r.saveReviewAnswer(state,"s1",state.sessions.s1.revision,"",true);
state = r.rateReviewCard(state,"s1",state.sessions.s1.revision,"fluent","e2",now,cards,preferences.studyTimezone);
const altered = r.pauseContent(state,[cards[0]],true);
assert.throws(() => r.undoLastReview(altered,"s1",altered.sessions.s1.revision,now), /另一页面更新/);
const shifted = r.changeReviewTimezone(state,"Pacific/Honolulu");
assert.equal(shifted.progress[cards[0].cardId].dueDate,"2026-03-10");
assert.equal(shifted.sessions.s1.timezone,"America/New_York");
assert.equal(shifted.sessions.s1.sessionDate,"2026-03-08");
// Fixed fixtures isolate the quota and ordering contract from scoring mechanics.
let quota = r.subscribeContent(r.emptyReviewState(),cards,now);
for (const item of cards.slice(0,38)) quota.progress[item.cardId] = {...quota.progress[item.cardId],stage:1,lastRating:"remembered",lastReviewedAt:"2026-03-01T12:00:00.000Z",intervalDays:1,dueDate:"2026-03-02"};
quota.events = cards.slice(0,8).map((item,index) => ({...state.events[1],eventId:`quota-${index}`,cardId:item.cardId,cardRevision:1,firstRating:false,occurredAt:now,revertedAt:null}));
let selected = r.selectReviewCards(quota,cards,preferences,now);
assert.equal(selected.length,12);
assert.equal(selected.filter((item) => quota.progress[item.cardId].lastReviewedAt===null).length,5);
assert.equal(selected.filter((item) => quota.progress[item.cardId].lastReviewedAt!==null).length,7);
quota.events.push(...cards.slice(38,41).map((item,index) => ({...state.events[1],eventId:`fresh-${index}`,cardId:item.cardId,cardRevision:1,firstRating:true,occurredAt:now,revertedAt:null})));
selected = r.selectReviewCards(quota,cards,preferences,now);
assert.equal(selected.length,9);
assert.equal(selected.filter((item) => quota.progress[item.cardId].lastReviewedAt===null).length,2);
for (const item of cards.slice(11,38)) quota.progress[item.cardId].paused = true;
selected = r.selectReviewCards(quota,cards,preferences,now);
assert.equal(selected.length,5,"到期只有3张时只选3旧+2新，不补超额新卡");
assert.equal(r.selectReviewCards(quota,cards,{...preferences,dailyLimit:10},now).length,0);
quota.progress[cards[8].cardId].lastRating="fluent";
quota.progress[cards[9].cardId].lastRating="forgotten";
quota.progress[cards[10].cardId].lastRating="unstable";
assert.deepEqual(json(r.selectReviewCards(quota,cards,preferences,now).slice(0,3).map((item) => item.cardId)),[cards[9].cardId,cards[10].cardId,cards[8].cardId]);
let extra = r.startReviewSession(r.emptyReviewState(),cards,preferences,now,"extra","extra",cards.map((item) => item.cardId));
assert.equal(extra.sessions.extra.cardsSnapshot.length,10);
extra = r.saveReviewAnswer(extra,"extra",1,"",true);
extra = r.rateReviewCard(extra,"extra",2,"remembered","extra-score",now,cards,preferences.studyTimezone);
assert.equal(extra.progress[cards[0].cardId].paused,false,"初次评分自动订阅");
assert.equal(r.isReviewState(extra),true);
// Content revision stays frozen during a live session and resets only on completion.
let revision = r.subscribeContent(r.emptyReviewState(),[cards[0]],now);
revision = r.startReviewSession(revision,[cards[0]],preferences,now,"revision");
const updatedCards=[card(0,2)];
assert.equal(r.synchronizeCards(revision,updatedCards).progress[cards[0].cardId].cardRevision,1);
revision = r.saveReviewAnswer(revision,"revision",1,"",true);
revision = r.rateReviewCard(revision,"revision",2,"fluent","old-version-score",now,updatedCards,preferences.studyTimezone);
assert.equal(revision.sessions.revision.status,"completed");
assert.equal(revision.progress[cards[0].cardId].cardRevision,2);
assert.equal(revision.progress[cards[0].cardId].lastRating,null);
assert.equal(revision.events[0].cardRevision,1);
assert.equal(r.isReviewState(revision),true);
revision = r.undoLastReview(revision,"revision",revision.sessions.revision.revision,now);
assert.equal(revision.sessions.revision.status,"active","最后一张也可撤销并重开");
assert.equal(revision.progress[cards[0].cardId].cardRevision,1);
assert.equal(r.isReviewState(revision),true);
revision=r.endReviewSession(revision,"revision",revision.sessions.revision.revision,now,updatedCards);
assert.equal(revision.progress[cards[0].cardId].cardRevision,2);
assert.equal(revision.sessions.revision.status,"ended");
assert.equal(r.isReviewState(revision),true);
assert.equal(r.isReviewState({...state,activeSessionId:"missing"}),false);
assert.equal(r.isReviewState({...state,events:[...state.events,state.events[0]]}),false);
assert.equal(r.isReviewState({...state,progress:{...state.progress,[cards[0].cardId]:{...state.progress[cards[0].cardId],stage:6}}}),false,"进度不允许脱离最近有效评分");
assert.equal(r.isReviewState({...state,events:state.events.map((event) => ({...event,after:{...event.after,dueDate:"2026-03-30"}}))}),false,"事件快照必须符合固定算法");
assert.throws(() => r.nextSchedule(1,"toString"));
const closed=r.endReviewSession(state,"s1",state.sessions.s1.revision,now,cards);
assert.equal(r.isReviewState(closed),true);
assert.equal(r.isReviewState({...closed,sessions:{...closed.sessions,s1:{...closed.sessions.s1,status:["ended"]}}}),false,"数组状态不能进入备份");
assert.equal(r.isReviewState({...r.emptyReviewState(),events:new Array(1)}),false,"稀疏事件数组不应抛错或通过");
assert.equal(r.isReviewState({...r.emptyReviewState(),events:new Array(100_001)}),false,"超过集合上限的空槽不能通过every");
assert.equal(r.isReviewState({...r.emptyReviewState(),sessions:Object.fromEntries(Array.from({length:100_001},(_,i)=>[`s-${i}`,closed.sessions.s1]))}),false);
const normalized=r.normalizeReviewState({...state,foreign:"do not retain"});
assert.equal(Object.hasOwn(normalized,"foreign"),false);
console.log("Review verified: fixed-v1, daily/new quotas, due ordering, calendar DST/midnight/timezone, pause, snapshots, reveal guard, idempotency, conflicts, undo, revision reset, validation");
